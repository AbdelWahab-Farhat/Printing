import 'package:flutter/foundation.dart';

/// أين يعيش خادمُ البثّ الحيّ (Reverb)، وبأيّ مفتاحٍ يُطرق.
///
/// **المفتاحُ عامّ، لا سرّ فيه.** هو اسمُ التطبيق عند الخادم؛ ما يحرس القنوات الخاصة توقيعٌ يمنحه
/// الـ API لكل قناةٍ على حدة بعد أن يسأل حارسَه — انظر [ChannelSigner].
@immutable
class RealtimeEndpoint {
  const RealtimeEndpoint({
    required this.scheme,
    required this.host,
    required this.key,
    this.port,
  });

  /// `ws` أو `wss`.
  final String scheme;

  final String host;

  /// فارغٌ يعني منفذَ المخطَّط الافتراضي — ٤٤٣ لـ`wss` خلف nginx في الإنتاج.
  final int? port;

  final String key;
}

/// يوقّع دخولَ قناةٍ خاصة: يرسل رقمَ المقبس واسمَ القناة إلى الـ API ويعود بالتوقيع.
///
/// **`null` هو الرفض**، أيّاً كان سببه — ٤٠٣ لقناةٍ ليست لك، أو انقطاعٌ في الطريق. لا فرق عند
/// المقبس: القناة لا تُفتح، والشاشة تبقى تعمل بالسحب كما كانت.
typedef ChannelSigner = Future<String?> Function(String socketId, String channelName);

/// الاتصالُ الحيّ بخادم Reverb، ببروتوكول Pusher.
///
/// **عقدٌ مجرّد لسببين.** الأول الطبقات: المستودعات تسمع من هنا ولا تعرف أيّ حزمةٍ تحته.
/// والثاني الاختبار: الـ Cubit يُختبر بتيارٍ مزيّف، بلا مقبسٍ ولا خادم.
abstract interface class RealtimeClient {
  /// أحداثُ [event] على القناة الخاصة [channel] (باسمها الكامل، `private-…`)، حمولةً مفكوكة.
  ///
  /// **الاشتراكُ يتبع المستمعين**: أوّلُ من يستمع يفتح الاتصال ويدخل القناة، وآخرُ من يغادر
  /// يخرج منها، ويُغلق الاتصالُ حين لا يبقى أحد. فالشاشة المغلقة لا تُبقي مقبساً مفتوحاً.
  ///
  /// **وحين لا يكون البثّ مُعدّاً** — لا مفتاح في `.env` — يعود تياراً لا يطلق شيئاً، والشاشات
  /// تعمل كما كانت قبل البثّ.
  Stream<Map<String, dynamic>> privateEvents(String channel, String event);

  /// يطلق كلما عاد الاتصال بعد انقطاع — عودةُ التطبيق من الخلفية، أو شبكةٌ سقطت ثم رجعت.
  ///
  /// **ما قيل في الانقطاع فات ولن يُعاد**، فمن يرسم شيئاً حيّاً يعيد قراءته عند هذا الحدث.
  Stream<void> get resumed;
}
