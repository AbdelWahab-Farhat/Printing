/// أيُّ اتجاهٍ تجري فيه جملةٌ واحدة — تقرّره الجملة، لا التطبيق.
///
/// هذا التطبيق عربيّ وكلّ شاشةٍ فيه مرصوفةٌ من اليمين إلى اليسار، وهو الصواب للعناوين والأزرار
/// والتسميات: كلّها لنا وكلّها عربية. **وصندوق الرسائل هو المكان الوحيد الذي يبطل فيه ذلك.** ما
/// يكتبه الشخص فيه هو ما يكتبه — «ok»، أو اسم ملف، أو وصفٌ إنجليزيّ من عميل — والجملة اللاتينية
/// المرسومة من اليمين إلى اليسار تخرج ونقطتُها في الطرف الخطأ وأقواسُها معكوسة. تُقرأ، وهي ظاهرةٌ
/// أنها ليست ما كُتب.
///
/// **والقاعدة قاعدةُ يونيكود نفسها — أوّل حرفٍ ذي اتجاه**، وهي ما يستعمله كلّ تطبيق محادثة في
/// هذه الهواتف: أوّلُ حرفٍ ينتمي إلى اتجاهٍ يقرّر للجملة كلّها. والأرقام والفراغات وعلامات
/// الترقيم ليست حروفاً فتُتخطّى، فتقود «5% discount» بالـ`d`، و«٥٪ خصم» بالـ«خ».
///
/// **و`null` حين لا حرف أصلاً** — صندوقٌ فارغ، أو رقم هاتف، أو وجهٌ ضاحكٌ وحده. و`null` ليست
/// «من اليسار إلى اليمين»: معناها *لا رأي لهذا النصّ*، فيُبقيه مَن يرسمه على اتجاه التطبيق بدل
/// أن يقلب رقماً إلى الإنجليزية.
///
/// وليست `Bidi` من `intl`: تلك تجيب بـbool، فيعود «لا حرف ذا اتجاه» و«من اليسار إلى اليمين»
/// جواباً واحداً — والتفريق بينهما هو سبب وجود هذا الملف.
library;

import 'dart:ui' show TextDirection;

/// الكتل العربية بالترتيب الذي يلقاها فيه القارئ، ثم العبرية: الحروف نفسها، والملحقان، وأشكال
/// العرض التي تصل منسوخةً من ملفات PDF — انظر `ArabicPresentationForms` التي تردّها إلى الحروف
/// التي خلفها.
const String _rightToLeft =
    r'֐-׿؀-ۿ܀-ݏݐ-ݿࢠ-ࣿ'
    r'יִ-﷿ﹰ-﻿';

/// اللاتينية، والأبجديات التي تُقرأ في اتجاهها: اللاتينية المشكولة، واليونانية، والسيريلية.
const String _leftToRight = r'A-Za-zÀ-ɏͰ-ϿЀ-ӿ';

final RegExp _firstLetter = RegExp('[$_rightToLeft$_leftToRight]');
final RegExp _readsRightToLeft = RegExp('[$_rightToLeft]');

extension ReadingDirection on String {
  /// اتجاه جريان هذا النصّ، أو `null` حين لا شيء فيه حرفاً.
  TextDirection? get readingDirection {
    final letter = _firstLetter.firstMatch(this)?[0];
    if (letter == null) return null;

    return _readsRightToLeft.hasMatch(letter) ? TextDirection.rtl : TextDirection.ltr;
  }
}
