import 'package:qr/qr.dart';

/// رمز QR بعد ترميزه: مصفوفة الوحدات وحدها — لا لون، ولا مقاس، ولا صورة.
///
/// **هذا هو ما تعنيه «إنشاء الرمز».** الترميز هو القرار الوحيد الذي لا رجعة فيه هنا: طول
/// المحتوى يقرّر إصدار الرمز، والإصدار يقرّر عدد الوحدات. اللون والخلفية والمقاس كلها طلاءٌ
/// فوق هذه المصفوفة، ولذلك لا شيء منها في هذا الصنف — تغييرها لا يستحق إعادة ترميز، وحملها
/// هنا كان سيجعل «رمزين مختلفين» من رمزٍ واحد بلونين.
///
/// **ليس نموذج Freezed**، خلافاً لـ §3، وهذا مقصود: لا JSON خلفه ولا API، ولا أحد ينسخه بـ
/// `copyWith`. وأهم من ذلك أن مساواة Freezed القيمية كانت ستقارن آلاف الوحدات عنصراً عنصراً في
/// كل `emit`، وهي مقارنة لا تجيب عن سؤال يسأله أحد: رمزٌ جديد كائنٌ جديد.
class QrCodeArt {
  const QrCodeArt._({
    required this.data,
    required this.moduleCount,
    required List<bool> modules,
  }) : _modules = modules;

  /// المحتوى كما رُمِّز — نصاً كما أدخله الموظف.
  ///
  /// **بلا أي تأويل: لا `tel:` ولا `https://` يُضاف.** رقم الهاتف يصير رمزاً يقرأه الماسح رقماً،
  /// والرابط يصير رابطاً لأن الموظف كتبه رابطاً. هذا بالضبط سلوك أداة الموقع (`qr.html`)، وهي
  /// المرجع؛ ومعالجة «هذا يبدو هاتفاً فلنجعله `tel:`» تخمينٌ يغيّر ما يخرج من الماسح دون أن يرى
  /// الموظف أنه تغيّر.
  final String data;

  /// عدد الوحدات على الضلع — بلا هامش الهدوء.
  final int moduleCount;

  /// المصفوفة مسطّحة صفاً بعد صف: `row * moduleCount + col`.
  final List<bool> _modules;

  /// أعلى مستوى تصحيح خطأ، تماماً كما في `qr.html` (`QRCode.CorrectLevel.H`).
  ///
  /// وهو الاختيار الصحيح لما يُطبع على كيس تحديداً: `H` يستعيد الرمز حتى لو تلف ثلثه، والكيس
  /// يُطوى ويُخدش ويُطبع بحبر يزيغ. الثمن رمزٌ أكبر قليلاً لنفس المحتوى.
  static const int errorCorrectLevel = QrErrorCorrectLevel.H;

  /// هامش الهدوء: أربع وحدات فارغة حول الرمز، كما تشترط المواصفة (ISO/IEC 18004).
  ///
  /// **أداة الموقع لا ترسمه، وهذه إضافةٌ مقصودة عليها.** الماسح يحتاج فراغاً حول الرمز ليعرف
  /// أين ينتهي؛ صورةٌ بلا هامش تُقرأ على شاشة بيضاء لأن الصفحة نفسها هي الهامش، ثم تتوقف عن
  /// القراءة في اللحظة التي تُقصّ فيها وتوضع على تصميم ملوّن — وهي بالضبط اللحظة التي تُصنع من
  /// أجلها هذه الأداة. الهامش شفافٌ حين تكون الخلفية شفافة، فلا يكلّف التصميم شيئاً.
  static const int quietZone = 4;

  /// يرمّز [data] كما هو.
  ///
  /// يرمي [InputTooLongException] إن كان المحتوى أطول مما يسعه أكبر رمز — و[GenerateQrCode] هي
  /// من تلتقطها.
  factory QrCodeArt.encode(String data) {
    final image = QrImage(QrCode.fromData(data: data, errorCorrectLevel: errorCorrectLevel));
    final count = image.moduleCount;

    return QrCodeArt._(
      data: data,
      moduleCount: count,
      modules: [
        for (var row = 0; row < count; row++)
          for (var col = 0; col < count; col++) image.isDark(row, col),
      ],
    );
  }

  /// عدد الوحدات على ضلع الصورة كاملةً — الرمز وهامشه.
  int get canvasModules => moduleCount + quietZone * 2;

  /// هل الوحدة عند [row]/[col] مطبوعة؟ الإحداثيات إحداثيات الرمز نفسه، لا الصورة: الهامش يضيفه
  /// الرسّام.
  bool isDark(int row, int col) => _modules[row * moduleCount + col];
}
