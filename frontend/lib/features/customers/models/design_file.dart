/// ملفٌّ يُحمَّل على الهاتف أو يُفتح خارج التطبيق — تصميمٌ في مكتبة العميل، أو ملفٌّ على تذكرة
/// تصميم.
///
/// **الشكلان واحدٌ عن قصد**: الخادم يرسل `DesignTicketFileResource` بحقول
/// `CustomerDesignResource` نفسها. وما يحتاجه «تحميل» و«فتح خارج التطبيق» من أيٍّ منهما هو هذه
/// الستة لا غير — فيُكتب الحفظ مرةً واحدة، ولا تُنسخ قاعدة اسم الملف لكل نموذج فتفترق النسختان.
abstract interface class DesignFile {
  int get id;

  /// ما يُسمّى به الملف حين يصل الهاتف. لا يكون فارغاً: الخادم يرجع إلى اسم الملف الأصلي.
  String get label;

  /// رابطٌ موقَّع تنتهي صلاحيته — يُقرأ ممّا تحمله الشاشة الآن، ولا يُحفظ.
  String? get fileUrl;

  String? get mimeType;
  String? get originalFilename;

  /// ما قرّره الخادم من بايتات الملف، وهو آخر ما يُرجع إليه حين لا امتداد ولا نوع.
  bool get isPdf;
}
