<?php

declare(strict_types=1);

namespace App\Domain\Investor\Enums;

/**
 * أين الفترةُ من عمرها — وثلاثُ حالات، أوسطُها هو الفرق كلُّه.
 *
 * **لا «مسودة» ولا «ملغاة».** الفترةُ لا تُنشأ بقرارٍ إنسانٍ لتُراجَع قبل اعتمادها؛ تُفتح آلياً
 * حين تُقفَل سابقتُها، فليس ثمّة لحظةٌ تكون فيها موجودةً وغيرَ عاملة. وإلغاؤها أشدّ استحالة:
 * الزمنُ مضى، والطلبيات التي وقعت فيها وقعت.
 *
 * و`Closed` **ليست حالةً تُبلَغ من نقطةِ تغييرِ حالة** — هي نتيجةُ `CloseInvestmentPeriod`
 * وحدها، بالانضباط نفسه الذي تمشي عليه `PurchaseOrderStatus::Completed` و`DealStatus::Closed`:
 * لها شروطٌ تُفحص، وفعلٌ يفحصها، فعرضُها كخيارٍ ثم رفضُه بابٌ لسوء فهم.
 *
 * ## ولماذا صارت ثلاثاً — §٠.٧ من المواصفة
 *
 * الفترةُ بعد موعدها تفعل شيئين لا تسع أيٌّ من الحالتين جمعَهما: **لا تقبل قيداً جديداً**
 * (طلبيةُ اليوم تاريخُها يضعها في التالية) **وتقبل ربحَ طلبياتها هي** (طلبيةُ سبتمبر تُسلَّم في
 * أكتوبر ربحُها لسبتمبر). و`Open` تقبل كلَّ شيء، و`Closed` ترفض كلَّ شيء.
 *
 * والسؤالان اللذان كان `acceptsPostings()` وحدَه يجيبهما صارا اثنين، ولا يجوز خلطُهما:
 *
 * ```
 * acceptsNewEntries()  ←  أتقع واقعةُ اليوم فيها؟        open وحدها
 * acceptsPostings()    ←  أيجوز أن يُكتب فيها صفٌّ؟      open و closing
 * ```
 */
enum PeriodStatus: string
{
    /** تستقبل الطلبيات والمشتريات والمصاريف، ولها وحدها هذه الصفة في أيّ لحظة. */
    case Open = 'open';

    /**
     * انتهت نافذتُها وبقيت لها طلبياتٌ لم تصل خاتمتَها.
     *
     * **لا تحبس أحداً**: نسبُها جُمِّدت، وأُفرِج عن ربح ما اكتملت شروطُه، والتاليةُ فُتحت في
     * موعدها. وما بقي أنها تنتظر طلبياتها هي — فيُقيَّد ربحُ كلٍّ منها فيها يوم يصل، ويُفرَج
     * عنه فوراً لأن مدّتها انقضت أصلاً.
     *
     * **وقد تنتظر أكثرُ من واحدة معاً**: أغسطس بطلبيةٍ عالقة وسبتمبر بأخرى. المفتوحةُ واحدةٌ
     * أبداً بحكم فهرسٍ في القاعدة، والمنتظِراتُ بلا عدد.
     */
    case Closing = 'closing';

    /** حُسبت أرقامُها وجُمِّدت، وأُفرِج عن أرباحها إلى محافظ أصحابها. */
    case Closed = 'closed';

    public function label(): string
    {
        return match ($this) {
            self::Open => 'مفتوحة',
            self::Closing => 'قيد الإغلاق',
            self::Closed => 'مغلقة',
        };
    }

    /**
     * أتقع واقعةُ اليوم في هذه الفترة؟
     *
     * طلبيةٌ تُكتب الآن، مصروفٌ تاريخُه اليوم، إيداعٌ يصل — كلُّها تسأل هذا السؤال، وجوابُه
     * المفتوحةُ وحدها. فالمنتظِرةُ انتهت نافذتُها الاقتصادية، وما يقع بعدها يقع فيما بعدها.
     */
    public function acceptsNewEntries(): bool
    {
        return $this === self::Open;
    }

    /**
     * أيجوز أن يُكتب في دفترها صفٌّ اليوم؟
     *
     * **وهو غيرُ السؤال الأول، والفرقُ بينهما هو الحالةُ الوسطى كلُّها.** ربحُ طلبيةِ سبتمبر
     * يُسلَّم في أكتوبر فيُكتب في سبتمبر: الواقعةُ الاقتصادية وقعت في نافذته، وإنما تأخّر
     * الاعترافُ بها. والمغلقةُ وحدها ترفض — أرقامُها جُمِّدت ومالُها خرج إلى جيوب أصحابه،
     * فالكتابةُ فيها تخالف رقماً وُقِّع عليه.
     */
    public function acceptsPostings(): bool
    {
        return $this === self::Open || $this === self::Closing;
    }
}
