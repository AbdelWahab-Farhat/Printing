<?php

declare(strict_types=1);

namespace App\Domain\Investor\Enums;

/**
 * كلُّ طريقٍ يتحرّك به نقدُ الصندوق — والاتجاهُ لا يسكن إشارةً أبداً.
 *
 * المبلغُ على الصفّ موجبٌ دائماً، تماماً كما في `order_payments` و`investor_wallet_entries`؛
 * وهذا الـ enum يقول ما **يعنيه** الصفّ، و{@see CashEntryType::isInflow()}
 * هو الموضع الوحيد الذي تُشتقّ منه الإشارة.
 *
 * **ولماذا دفترٌ أصلاً بدل رقمٍ محسوب:** «كم يملك الصندوق نقداً» سؤالٌ يُسأل عند كل شراء، وعند كل
 * سحب، وعند كل حافّة فترة تُعاد فيها قسمةُ النسب. اشتقاقُه في كل مرّة من المحافظ وأوامر الشراء
 * ودفعات الطلبيات حسابٌ فوق حساب، ولا شيء فيه يمكن عدُّه ومطابقتُه بورقة. الدفترُ رقمٌ يُمشى مرّة
 * ويُراجَع.
 *
 * **ولا عمود رصيد**، كبقيّة دفاتر هذا النظام: الرصيد مشيُ الصفوف، والتصحيح صفٌّ عكسيّ.
 *
 * ## النقدُ ليس القيمة — وهذا الفرق هو نصفُ الميزة
 *
 * الصندوق يعترف بالربح عند **التسليم**، والعميلُ يدفع بعد ذلك بأسابيع. فلو حرّكنا الخزينة عند
 * التسليم لسمحنا بالشراء والسحب من مالٍ لم يصل. لذلك:
 *
 * - **الخزينة تتحرّك عند التحصيل** ({@see self::SaleProceeds} مصدرُه `order_payment`).
 * - و**المستحقّ** — ما سُلِّم ولم يُحصَّل — يدخل **قيمة** الصندوق ولا يدخل نقدَه.
 *
 * فسقفُ الشراء وسقفُ السحب يقرآن النقد وحده، وقسمةُ النسب تقرأ القيمة كاملة.
 */
enum CashEntryType: string
{
    /** مستثمرٌ سلّم مالاً — مصدرُه صفُّ الإيداع في دفتر محفظته. */
    case Deposit = 'deposit';

    /** شراءُ بضاعةٍ بمال الصندوق — مصدرُه أمرُ الشراء. */
    case Purchase = 'purchase';

    /** مصروفٌ على الصندوق — مصدرُه صفُّ المصروف. */
    case Expense = 'expense';

    /** تحصيلُ ثمن بيعٍ من عميل — مصدرُه دفعةُ الطلبية، لا الطلبيةُ نفسها. */
    case SaleProceeds = 'sale_proceeds';

    /** أرباحٌ خرجت إلى مستثمر — مصدرُه صفُّ السحب في دفتر محفظته. */
    case ProfitPayout = 'profit_payout';

    /** نصيبُ الشركة من ربح فترةٍ أُغلقت — مصدرُه صفُّ الفترة. */
    case CompanyPayout = 'company_payout';

    /** رأسُ مالٍ يعود إلى مستثمر بعد انقضاء مدة حجزه — مصدرُه صفُّ محفظته. */
    case CapitalReturn = 'capital_return';

    /**
     * المطبعةُ اشترت سادةَ الصندوق عند باب المخزن — مصدرُه سطرُ الطلبية التي سحبتها.
     *
     * الثمنُ كاملاً (`سعر السادة × الكمية`) لا الهامش: التكلفةُ خرجت من هذه الخزينة يوم الشراء
     * فتعود إليها مع ربحها، ثم يخرج الهامشُ إلى المحافظ بـ{@see self::ProfitPayout}. ولا علاقةَ
     * له بما دفعه العميل: «استلم الزبون ما استلمش، المطبعة تتحمّل».
     */
    case StockSoldToPress = 'stock_sold_to_press';

    /**
     * مالُ صفقةٍ قديمة ينتقل من صندوق الشركة إلى خزينة الصندوق حين تدخله — §٠.٩.
     *
     * مصدرُه صفُّ المحفظة الذي يقابله: الاشتراكُ الذي صار وحدات (نقدُه المحقَّق)، أو الإفراجُ
     * الذي صار ربحاً في محفظته (فسحبُه يخرج من هنا ولا يأكل نقدَ الصندوق).
     */
    case LegacyTransfer = 'legacy_transfer';

    /** يُبطل صفّاً واحداً سابقاً، حاملاً مبلغَه كما هو. */
    case Reversal = 'reversal';

    public function label(): string
    {
        return match ($this) {
            self::Deposit => 'إيداع رأس مال',
            self::Purchase => 'شراء بضاعة',
            self::Expense => 'مصروف',
            self::SaleProceeds => 'تحصيل مبيعات',
            self::ProfitPayout => 'صرف أرباح',
            self::CompanyPayout => 'نصيب الشركة',
            self::CapitalReturn => 'إرجاع رأس مال',
            self::StockSoldToPress => 'بيع سادة للمطبعة',
            self::LegacyTransfer => 'تحويل من صفقة سابقة',
            self::Reversal => 'عكس حركة',
        };
    }

    /**
     * أيزيد هذا الصفُّ النقدَ أم ينقصه.
     *
     * والعكسُ ليس له اتجاهٌ خاصّ به — يأخذ نقيضَ اتجاه الصفّ الذي يُبطله، ولذلك يُجيب هنا بـ
     * `false` ولا يُقرأ منه شيء: قارئُه الوحيد يمرّ على `reversedEntry` أولاً.
     */
    public function isInflow(): bool
    {
        return match ($this) {
            self::Deposit, self::SaleProceeds, self::StockSoldToPress, self::LegacyTransfer => true,
            default => false,
        };
    }

    /** أيجوز أن يكتبه إنسانٌ بيده؟ */
    public function isRecordableByHand(): bool
    {
        // لا واحد. كلُّ صفٍّ في هذه الخزينة أثرُ حدثٍ في مكانٍ آخر — إيداعٍ أو أمرِ شراءٍ أو
        // مصروفٍ أو دفعةِ طلبية — ومصدرُه إلزاميّ. صفٌّ يُكتب بلا مصدرٍ نقدٌ لا يعرف أحدٌ من أين
        // جاء، وهو بالضبط ما تمنعه هذه الميزة في كل دفترٍ آخر لها.
        return false;
    }

    /** الأنواع التي يجب أن تسمّي مصدرها — وهي كلُّها إلا العكس. */
    public function needsASource(): bool
    {
        return $this !== self::Reversal;
    }
}
